import json, os, random, re

ROOT = os.path.join(os.path.dirname(__file__), '..')
KANJI = re.compile(r'[一-龯々]')
KANA = re.compile(r'^[ぁ-ゖァ-ヺー]+$')


DAKU = dict(zip('かきくけこさしすせそたちつてとはひふへほ', 'がぎぐげござじずぜぞだぢづでどばびぶべぼ'))
DAKU.update({v: k for k, v in list(DAKU.items())})
def near_readings(r):
    """Lectures voisines, comme dans les vraies épreuves : voisement, voyelle longue, petit っ, ゃゅょ."""
    out = set()
    for i, ch in enumerate(r):
        if ch in DAKU:
            out.add(r[:i] + DAKU[ch] + r[i + 1:])
        if ch == 'っ':
            out.add(r[:i] + r[i + 1:])
        if ch in 'うい' and i > 0:
            out.add(r[:i] + r[i + 1:])
        if ch in 'ょゅゃ':
            out.add(r[:i] + {'ょ': 'よ', 'ゅ': 'ゆ', 'ゃ': 'や'}[ch] + r[i + 1:])
        if ch in 'こそとほよ' and i + 1 < len(r) and r[i + 1] != 'う':
            out.add(r[:i + 1] + 'う' + r[i + 1:])
        if i > 0 and ch in 'かきくけこさしすせそたちつてとぱぴぷぺぽ' and r[i - 1] != 'っ':
            out.add(r[:i] + 'っ' + r[i:])
    out.discard(r)
    return sorted(x for x in out if x and not x.startswith('っ'))

def load(lv):
    return json.load(open(os.path.join(ROOT, f'content/{lv}/{lv}.json'), encoding='utf-8'))

def lessons(level):
    return [l for w in level['worlds'] for c in w['chapters'] for l in c['lessons']]

def pos(front):
    if front.endswith('ます') or re.search(r'[うくぐすつぬぶむる]$', front): return 'verb'
    if front.endswith('い') and not front.endswith('せい'): return 'adj'
    return 'noun'

def transcript(audio):
    return 'Transcription : ' + ' / '.join(l.split('|', 1)[1] for l in audio.split('\n'))

# ───────── Épreuves rédigées : reformulation, lecture, écoute (tâche et points essentiels) ─────────
def P(jp, right, *wrong):
    return {'jp': jp, 'choices': [right, *wrong], 'answer': right, 'explanation': f'Même sens : {right}'}

def R(passage, text, right, *wrong):
    return {'passage': passage, 'text': text, 'choices': [right, *wrong], 'answer': right, 'explanation': f'Réponse : {right}'}

def A(audio, right, *wrong):
    q = audio.strip().split('\n')[-1].split('|', 1)[1]
    return {'audio': audio.strip(), 'text': q, 'choices': [right, *wrong], 'answer': right, 'explanation': transcript(audio.strip())}


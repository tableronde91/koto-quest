def ortho_distractors(f, pool, rng):
    """Mots de même longueur, en priorité ceux qui partagent un kanji avec la bonne réponse."""
    share = [w for w in pool if len(w) == len(f) and set(w) & set(f) and w != f]
    size = [w for w in pool if len(w) == len(f) and w not in share]
    rest = [w for w in pool if w not in share and w not in size]
    picked = rng.sample(share, min(3, len(share)))
    for group in (size, rest):
        if len(picked) < 3:
            picked += rng.sample(group, min(3 - len(picked), len(group)))
    return picked

def auto_parts(lv, rng):
    level = load(lv)
    ls = lessons(level)
    vocab = [it for l in ls for it in l['items'] if it['kind'] == 'vocabulary' and KANJI.search(it['front']) and KANA.match(it['reading'] or '') and not it['front'].startswith('〜')]
    examples = [e['jp'] for l in ls for e in l['examples']]
    readings = sorted({v['reading'] for v in vocab})
    out = {'kanji_reading': [], 'orthography': [], 'context': []}
    for v in vocab:
        f = v['front']
        ex = next((e for e in examples if e.count(f) == 1 and not KANJI.search(e.replace(f, '')[:0])), None)
        if not ex:
            continue
        near = [r for r in near_readings(v['reading']) if r not in readings]
        if len(near) >= 3 and len(v['reading']) >= 3:
            out['kanji_reading'].append({'jp': ex.replace(f, '{{' + f + '}}'), 'choices': [v['reading'], *rng.sample(near, 3)], 'answer': v['reading'], 'explanation': f'「{f}」 se lit 「{v["reading"]}」.'})
        same = [o['front'] for o in vocab if o['front'] != f and pos(o['front']) == pos(f) and o['front'] not in ex]
        if len(same) >= 3:
            out['orthography'].append({'jp': ex.replace(f, '{{' + v['reading'] + '}}'), 'choices': [f, *ortho_distractors(f, same, rng)], 'answer': f, 'explanation': f"「{v['reading']}」 s'écrit 「{f}」."})
            out['context'].append({'jp': ex.replace(f, '（　　）'), 'choices': [f, *rng.sample(same, 3)], 'answer': f, 'explanation': f'Phrase complète : {ex}'})
    grammar, compo, resp = [], [], []
    for l in ls:
        for e in l.get('exercises', []):
            if e['type'] in ('fill_blank', 'particle_choice') and e['sentence'].count('＿') == 1:
                grammar.append({'jp': e['sentence'].replace('＿', '（　　）'), 'choices': list(e['choices']), 'answer': e['answer'], 'explanation': e['explanation']})
            elif e['type'] == 'sentence_order' and len(e['answer']) in (4, 5, 6) and len(set(e['answer'])) == len(e['answer']):
                t = e['answer']
                pre, mid, post = (t[:1], t[1:5], t[5:]) if len(t) > 4 else ([], t, [])
                jp = ' '.join([*pre, '＿＿', '＿＿', '★', '＿＿', *post])
                compo.append({'jp': jp, 'choices': list(mid), 'answer': mid[2], 'explanation': 'Ordre : ' + ' / '.join(mid) + ' → ' + ' '.join(t)})
            elif e['type'] == 'dialogue_choice':
                lines = [('F' if i % 2 == 0 else 'M') + '|' + x['jp'] for i, x in enumerate(e['lines'])]
                resp.append({'audio': '\n'.join(lines), 'choices': list(e['choices']), 'answer': e['answer'], 'explanation': e['explanation']})
    out.update(grammar_form=grammar, composition=compo, response=resp)
    for k in out:
        rng.shuffle(out[k])
    return out

